export const STRINGS = { fr, en };

export function detectLang(): Lang {
  const saved = localStorage.getItem('ar-lang');
  if (saved === 'fr' || saved === 'en') return saved;
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}
